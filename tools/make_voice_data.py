#!/usr/bin/env python3
"""Writes js/voice-data.js from docs/U33_VOICE_MAP.json (re-run after the voice script changes)."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEY = {'GHOST': 'ghost', 'ZAVALA': 'zavala', 'IKORA REY': 'ikora', 'CAYDE-6': 'cayde', 'ERIS MORN': 'eris', 'RASPUTIN': 'rasputin', 'THE SPIDER': 'spider',
       'PETRA VENJ': 'petra', 'MARA SOV': 'mara', 'RIVEN': 'riven', 'EMPEROR CALUS': 'calus', 'ASHER MIR': 'asher', 'PSION HERALD': 'psion',
       'KADI 55-30': 'kadi', 'CROTA': 'crota'}
NO_COMMS = {'GHOST', 'RIVEN', 'PSION HERALD'}
m = json.load(open(os.path.join(ROOT, 'docs/U33_VOICE_MAP.json'), encoding='utf-8'))
rows = []
for n in sorted(m):
    v = m[n]
    rows.append([n, KEY[v['speaker']], v['text'], 0 if v['speaker'] in NO_COMMS else 1])
out = '// U33 Transmissions: every NPC voice line. Generated by tools/make_voice_data.py from docs/U33_VOICE_MAP.json. Do not edit by hand.\n'
out += '// [id, speaker key (js/story.js SPEAKERS), spoken text, 1 if a comms version exists]. Files: assets/voice/<id>.mp3 and assets/voice/comms/<id>.mp3.\n'
out += 'export const VOICE_LINES = [\n' + ''.join('  ' + json.dumps(r, ensure_ascii=False) + ',\n' for r in rows) + '];\n'
open(os.path.join(ROOT, 'js/voice-data.js'), 'w', encoding='utf-8').write(out)
print(len(rows), 'lines')
